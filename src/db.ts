import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import Database from 'better-sqlite3';

export type DB = Database.Database;

// All timestamps are ISO-8601 UTC strings, e.g. "2026-11-15T09:30:00.000Z".
const SCHEMA = `
CREATE TABLE IF NOT EXISTS events (
  event_id       TEXT NOT NULL,
  calendar_id    TEXT NOT NULL,
  client_name    TEXT NOT NULL,
  title          TEXT NOT NULL DEFAULT '',
  start_utc      TEXT NOT NULL,
  end_utc        TEXT NOT NULL,
  status         TEXT NOT NULL,          -- confirmed | tentative | cancelled
  meet_link      TEXT,
  attendees_json TEXT NOT NULL DEFAULT '[]',
  updated_at     TEXT NOT NULL,
  first_seen_utc TEXT NOT NULL,          -- set on first insert, never updated
  PRIMARY KEY (event_id, calendar_id)
);

CREATE INDEX IF NOT EXISTS idx_events_start ON events (start_utc);

-- calendar_id is part of the key: one Google invite can sit on several client
-- calendars with the same event_id, and each client group needs its own reminder.
CREATE TABLE IF NOT EXISTS sent_reminders (
  event_id    TEXT NOT NULL,
  calendar_id TEXT NOT NULL,
  start_utc   TEXT NOT NULL,
  offset_min  INTEGER NOT NULL,
  sent_at     TEXT NOT NULL,
  status      TEXT NOT NULL DEFAULT 'sent' CHECK (status IN ('sent', 'missed')),
  UNIQUE (event_id, calendar_id, start_utc, offset_min)
);

-- Small key/value store, e.g. last_successful_sync for the health check.
CREATE TABLE IF NOT EXISTS kv (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- Configuration managed in the admin UI (see src/store.ts).
CREATE TABLE IF NOT EXISTS closers (
  id         INTEGER PRIMARY KEY,
  name       TEXT NOT NULL,
  email      TEXT NOT NULL UNIQUE,       -- lowercased
  whatsapp   TEXT NOT NULL,              -- digits only
  active     INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS clients (
  id                INTEGER PRIMARY KEY,
  name              TEXT NOT NULL,
  calendar_id       TEXT NOT NULL UNIQUE,
  whatsapp_group_id TEXT NOT NULL,       -- ends in @g.us
  active            INTEGER NOT NULL DEFAULT 1,
  created_at        TEXT NOT NULL,
  updated_at        TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS settings (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,              -- JSON
  updated_at TEXT NOT NULL
);

-- The superadmin comes from the environment and is never stored here.
CREATE TABLE IF NOT EXISTS admin_users (
  email      TEXT PRIMARY KEY,           -- lowercased
  role       TEXT NOT NULL CHECK (role IN ('admin')),
  added_by   TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS admin_sessions (
  token_hash TEXT PRIMARY KEY,           -- sha256 of the cookie token
  email      TEXT NOT NULL,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL
);

-- People directory (replaces admin_users, which is kept but no longer used).
CREATE TABLE IF NOT EXISTS people (
  id              INTEGER PRIMARY KEY,
  email           TEXT NOT NULL UNIQUE,   -- lowercased
  name            TEXT NOT NULL,
  whatsapp        TEXT,                   -- digits only, or NULL
  role            TEXT NOT NULL CHECK (role IN ('admin', 'member')),
  active          INTEGER NOT NULL DEFAULT 1,
  notify_target   TEXT NOT NULL DEFAULT 'default' CHECK (notify_target IN ('default', 'group', 'dm')),
  notify_group_id TEXT,                   -- ends in @g.us when notify_target = 'group'
  created_at      TEXT NOT NULL,
  updated_at      TEXT NOT NULL,
  added_by        TEXT                    -- who created the person; NULL for rows migrated without it
);

-- One pending email sign-in code per address; only its sha256 is stored.
CREATE TABLE IF NOT EXISTS login_codes (
  email      TEXT PRIMARY KEY,
  code_hash  TEXT NOT NULL,
  attempts   INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS access_grants (
  id                 INTEGER PRIMARY KEY,
  grantee_person_id  INTEGER NOT NULL REFERENCES people(id),
  owner_person_id    INTEGER NOT NULL REFERENCES people(id),
  level              TEXT NOT NULL CHECK (level IN ('view', 'edit')),
  created_by         TEXT NOT NULL,
  created_at         TEXT NOT NULL,
  UNIQUE (grantee_person_id, owner_person_id)
);

CREATE TABLE IF NOT EXISTS tasks (
  id                  TEXT PRIMARY KEY,   -- UUID v4, may be generated by the client
  owner_person_id     INTEGER NOT NULL REFERENCES people(id),
  title               TEXT NOT NULL,
  notes               TEXT NOT NULL DEFAULT '',
  status              TEXT NOT NULL DEFAULT 'todo' CHECK (status IN ('todo', 'in_progress', 'done')),
  priority            TEXT NOT NULL DEFAULT 'medium' CHECK (priority IN ('low', 'medium', 'high', 'urgent')),
  due_at              TEXT,               -- UTC ISO
  checklist_json      TEXT NOT NULL DEFAULT '[]',
  snoozed_until       TEXT,
  completed_at        TEXT,
  first_alert_sent_at TEXT,
  last_notified_at    TEXT,
  created_by          TEXT NOT NULL,
  created_at          TEXT NOT NULL,
  updated_at          TEXT NOT NULL,
  version             INTEGER NOT NULL DEFAULT 1,
  deleted_at          TEXT
);
CREATE INDEX IF NOT EXISTS idx_tasks_owner_status ON tasks (owner_person_id, status);
CREATE INDEX IF NOT EXISTS idx_tasks_due ON tasks (due_at);
CREATE INDEX IF NOT EXISTS idx_tasks_updated ON tasks (updated_at);

CREATE TABLE IF NOT EXISTS task_activity (
  id      INTEGER PRIMARY KEY,
  task_id TEXT NOT NULL,
  at      TEXT NOT NULL,
  actor   TEXT NOT NULL,
  action  TEXT NOT NULL,
  details TEXT NOT NULL DEFAULT '{}'      -- JSON, never secrets
);
CREATE INDEX IF NOT EXISTS idx_task_activity_task ON task_activity (task_id, id);

CREATE TABLE IF NOT EXISTS task_digests (
  id              INTEGER PRIMARY KEY,
  owner_person_id INTEGER NOT NULL,
  sent_at         TEXT NOT NULL,
  target          TEXT NOT NULL,
  task_ids        TEXT NOT NULL           -- JSON array
);

CREATE TABLE IF NOT EXISTS task_nudge_state (
  owner_person_id INTEGER PRIMARY KEY,
  next_digest_at  TEXT,
  last_digest_at  TEXT
);

CREATE TABLE IF NOT EXISTS audit_log (
  id      INTEGER PRIMARY KEY,
  at      TEXT NOT NULL,
  actor   TEXT NOT NULL,
  action  TEXT NOT NULL,
  details TEXT NOT NULL                  -- JSON, never secrets
);
`;

export function setKv(db: DB, key: string, value: string): void {
  db.prepare(
    `INSERT INTO kv (key, value, updated_at) VALUES (?, ?, ?)
     ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at`,
  ).run(key, value, new Date().toISOString());
}

export function getKv(db: DB, key: string): string | undefined {
  const row = db.prepare(`SELECT value FROM kv WHERE key = ?`).get(key) as { value: string } | undefined;
  return row?.value;
}

/**
 * One-off: databases created before calendar_id was added have the old
 * sent_reminders table. It held no real data, so drop it and let SCHEMA recreate it.
 */
function dropLegacySentReminders(db: DB): void {
  const cols = db.prepare(`PRAGMA table_info(sent_reminders)`).all() as { name: string }[];
  if (cols.length > 0 && !cols.some((c) => c.name === 'calendar_id')) {
    db.exec(`DROP TABLE sent_reminders`);
  }
}

function hasColumn(db: DB, table: string, column: string): boolean {
  const cols = db.prepare(`PRAGMA table_info(${table})`).all() as { name: string }[];
  return cols.some((c) => c.name === column);
}

/** Adds columns introduced after a database was created (CREATE TABLE IF NOT EXISTS won't). */
function addMissingColumns(db: DB): void {
  db.transaction(() => {
    if (!hasColumn(db, 'events', 'first_seen_utc')) {
      db.exec(`ALTER TABLE events ADD COLUMN first_seen_utc TEXT`);
      db.exec(`UPDATE events SET first_seen_utc = updated_at WHERE first_seen_utc IS NULL`);
    }
    // Sessions: members get 30-day sliding sessions (sliding = 1, extended_at = last extension).
    if (!hasColumn(db, 'admin_sessions', 'sliding')) {
      db.exec(`ALTER TABLE admin_sessions ADD COLUMN sliding INTEGER NOT NULL DEFAULT 0`);
    }
    if (!hasColumn(db, 'admin_sessions', 'extended_at')) {
      db.exec(`ALTER TABLE admin_sessions ADD COLUMN extended_at TEXT`);
    }
    if (!hasColumn(db, 'people', 'added_by')) {
      db.exec(`ALTER TABLE people ADD COLUMN added_by TEXT`);
    }
    // Which product issued the session: a reminders-console session is never valid in Nudge and vice versa.
    if (!hasColumn(db, 'admin_sessions', 'product')) {
      db.exec(`ALTER TABLE admin_sessions ADD COLUMN product TEXT NOT NULL DEFAULT 'reminders'`);
    }
    if (!hasColumn(db, 'sent_reminders', 'status')) {
      db.exec(`ALTER TABLE sent_reminders ADD COLUMN status TEXT NOT NULL DEFAULT 'sent' CHECK (status IN ('sent', 'missed'))`);
    }
  })();
}

export const KV_PEOPLE_MIGRATED_AT = 'people_migrated_at';

/**
 * One-off, idempotent: copies every admin_users row into people (role 'admin', name = email local part).
 * Guarded by a kv flag so that an admin later removed from people is never resurrected from the old table.
 */
export function migrateAdminUsers(db: DB): number {
  return db.transaction(() => {
    if (getKv(db, KV_PEOPLE_MIGRATED_AT)) return 0;
    const now = new Date().toISOString();
    const rows = db.prepare(`SELECT email, created_at, added_by FROM admin_users`).all() as { email: string; created_at: string; added_by: string | null }[];
    const ins = db.prepare(
      `INSERT OR IGNORE INTO people (email, name, whatsapp, role, active, notify_target, notify_group_id, created_at, updated_at, added_by)
       VALUES (?, ?, NULL, 'admin', 1, 'default', NULL, ?, ?, ?)`,
    );
    let n = 0;
    for (const r of rows) {
      const email = r.email.trim().toLowerCase();
      n += ins.run(email, email.split('@')[0] || email, r.created_at, now, r.added_by ?? null).changes;
    }
    setKv(db, KV_PEOPLE_MIGRATED_AT, now);
    return n;
  })();
}

/** Opens (creating if needed) the SQLite database and ensures the schema exists. */
export function openDb(path: string): DB {
  if (path !== ':memory:') mkdirSync(dirname(path), { recursive: true });
  const db = new Database(path);
  // busy_timeout first: two processes (reminders + nudge) may open the same file at the same moment.
  db.pragma('busy_timeout = 5000');
  db.pragma('journal_mode = WAL'); // safe concurrent reads, durable writes
  db.pragma('synchronous = NORMAL');
  // Every migration is idempotent and runs in one IMMEDIATE transaction, so simultaneous startups are safe.
  db.transaction(() => {
    dropLegacySentReminders(db);
    db.exec(SCHEMA);
    addMissingColumns(db);
    migrateAdminUsers(db);
  }).immediate();
  return db;
}
